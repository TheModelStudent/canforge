bool is_ident_start(char c) noexcept {
  const auto u = static_cast<unsigned char>(c);
  return std::isalpha(u) != 0 || c == '_' ||
         u >= 0x80;  // permit UTF-8 continuation bytes inside names
}

bool is_ident_continue(char c) noexcept {
  const auto u = static_cast<unsigned char>(c);
  return std::isalnum(u) != 0 || c == '_' || u >= 0x80;
}

bool is_digit(char c) noexcept {
  return c >= '0' && c <= '9';
}

std::size_t utf8_sequence_length(const unsigned char* p, std::size_t left) noexcept {
  const unsigned char c = p[0];
  if (c < 0x80u) {
    return 1;
  }
  std::size_t need = 0;
  if ((c & 0xE0u) == 0xC0u) {
    need = 2;
  } else if ((c & 0xF0u) == 0xE0u) {
    need = 3;
  } else if ((c & 0xF8u) == 0xF0u) {
    need = 4;
  } else {
    return 0;  // continuation byte or invalid lead
  }
  if (need > left) {
    return 0;
  }
  for (std::size_t i = 1; i < need; ++i) {
    if ((p[i] & 0xC0u) != 0x80u) {
      return 0;
    }
  }
  return need;
}

bool is_valid_utf8(const std::string& s) noexcept {
  const auto* p = reinterpret_cast<const unsigned char*>(s.data());  // NOLINT
  std::size_t i = 0;
  while (i < s.size()) {
    const std::size_t n = utf8_sequence_length(p + i, s.size() - i);
    if (n == 0) {
      return false;
    }
    i += n;
  }
  return true;
}

/// Latin-1 to UTF-8. Every byte 0x00..0xFF maps to exactly one code point, so
/// this never fails -- which is precisely why it is a safe fallback.
std::string latin1_to_utf8(const std::string& in) {
  std::string out;
  out.reserve(in.size() + in.size() / 4u);
  for (const char ch : in) {
    const auto c = static_cast<unsigned char>(ch);
    if (c < 0x80u) {
      out.push_back(static_cast<char>(c));
    } else {
      out.push_back(static_cast<char>(0xC0u | (c >> 6u)));
      out.push_back(static_cast<char>(0x80u | (c & 0x3Fu)));
    }
  }
  return out;
}

